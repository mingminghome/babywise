function deepMerge(a: MessageTree, b: MessageTree): MessageTree {
  const out: MessageTree = { ...a };
  for (const [k, v] of Object.entries(b)) {
    const prev = out[k];
    if (
      v &&
      typeof v === 'object' &&
      prev &&
      typeof prev === 'object' &&
      !Array.isArray(v) &&
      !Array.isArray(prev)
    ) {
      out[k] = deepMerge(prev as MessageTree, v as MessageTree);
    } else {
      out[k] = v;
    }
  }
  return out;
}

